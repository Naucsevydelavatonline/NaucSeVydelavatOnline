// Centrální registr doporučených/affiliate nástrojů.
//
// Proč takhle: každá "možnost vydělávání" v src/content/methods odkazuje
// na nástroj přes `toolId` (ne přes přímou URL). Když se změní affiliate
// odkaz nebo přibude nová partnerská smlouva, upravuje se JEN tento
// soubor – ne desítky markdown souborů. Komponenta `AffiliateLink.astro`
// tento registr čte:
//   - `affiliateStatus: 'active'` + vyplněné `affiliateUrl` → odkaz vede
//     na affiliate/referral URL a zobrazí se u něj disclosure "(partnerský
//     odkaz)" / "(referral odkaz)" podle `affiliateType`.
//   - `affiliateStatus: 'pending'` nebo `'none'` → odkaz vede vždy na
//     `officialUrl`, bez jakéhokoliv disclosure textu. Nikdy si
//     nevymýšlíme tracking/affiliate URL dřív, než reálně existuje.
//
// `recommendedFor` je orientační zpětný seznam metod, které nástroj
// používají (pro přehled/údržbu) – zdroj pravdy je vždy `tools[]` na
// dané metodě v src/content/methods, kde se navíc řeší `role`
// ("core" doporučený základ / "alternative").
//
// Později: tahle struktura se dá 1:1 přesunout do DB tabulky
// (+ clicks, conversions...), aniž by se muselo měnit API komponenty.

export type AffiliateType = 'affiliate' | 'referral' | 'none';
export type AffiliateStatus = 'active' | 'pending' | 'none';

export interface AffiliateTool {
  id: string;
  name: string;
  description: string;
  /** Volný kategorizační štítek (jen pro přehled v tomto souboru, ne pro filtrování na webu). */
  category: string;
  /** Konkrétní situace, ve kterých nástroj dává smysl. */
  useCases: string[];
  /** Stručná, orientační cena – bez slibování konkrétních částek, které se rychle mění. */
  pricingInfo: string;
  freePlan: boolean;
  mobileFriendly: boolean;
  affiliateType: AffiliateType;
  affiliateStatus: AffiliateStatus;
  /** Affiliate/referral URL – vyplněná JEN když `affiliateStatus === 'active'`. */
  affiliateUrl?: string;
  /** Běžný (neafiliovaný) odkaz na nástroj – vždy vyplněný. */
  officialUrl: string;
  commission?: string;
  commissionDuration?: string;
  cookieDuration?: string;
  /** Orientační zpětný seznam slugů metod z src/content/methods, které nástroj zmiňují. */
  recommendedFor: string[];
  /** 1 = přirozený "hlavní" nástroj pro svou kategorii, 2+ = spíš alternativa/doplněk. */
  priority: number;
}

